/*
   Empty City - x86 raw global-blob experiment.

   Apart from main(), the TLS callback, VEH handler, and payload are all
   numeric byte arrays in ordinary RW .data. Static analysis can still find
   the callback through the PE TLS directory; data is not inherently hidden.
*/

#pragma comment(linker, "/SUBSYSTEM:CONSOLE")
#pragma comment(linker, "/ENTRY:main")
#pragma comment(linker, "/NODEFAULTLIB")
#pragma comment(linker, "/EXPORT:main=_main")

#pragma section(".CRT$XLA", read)
#pragma section(".CRT$XLB", read)
#pragma section(".CRT$XLZ", read)
#pragma section(".rdata$T", read)

/* Reference IAT slots, not function addresses: no .text import jump stubs. */
extern PVOID iat_GetStdHandle;
extern PVOID iat_WriteFile;
extern PVOID iat_ExitProcess;
