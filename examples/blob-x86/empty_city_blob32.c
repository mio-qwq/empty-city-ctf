#pragma comment(linker, "/alternatename:_iat_ExitProcess=__imp__ExitProcess@4")
#pragma comment(linker, "/alternatename:_iat_AddVectoredExceptionHandler=__imp__AddVectoredExceptionHandler@8")

enum {
    CALLBACK_OFFSET = 0x000,
    HANDLER_OFFSET = 0x100,
    PAYLOAD_OFFSET = 0x200,
    MESSAGE_OFFSET = 0x400,
    API_OFFSET = 0x440,
    API_GETSTD = 0,
    API_WRITEFILE = 1,
    API_EXITPROCESS = 2,
    API_ADDVEH = 3
};

typedef struct BLOB32 {
    unsigned char callback[0x100];
    unsigned char handler[0x100];
    unsigned char payload[0x200];
    unsigned char message[0x40];
    PVOID api[4];
} BLOB32;

/* Machine-code displacements below rely on this exact x86 layout. */
C_ASSERT(offsetof(BLOB32, callback) == CALLBACK_OFFSET);
C_ASSERT(offsetof(BLOB32, handler) == HANDLER_OFFSET);
C_ASSERT(offsetof(BLOB32, payload) == PAYLOAD_OFFSET);
C_ASSERT(offsetof(BLOB32, message) == MESSAGE_OFFSET);
C_ASSERT(offsetof(BLOB32, api) == API_OFFSET);
C_ASSERT(offsetof(CONTEXT, Eip) == 0xB8);
C_ASSERT(sizeof(PVOID) == 4);

